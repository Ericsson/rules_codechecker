"""
Drives common.check_results() against a real CodeChecker result.txt fixture.

Intended to be used as the main of a py_test Bazel target, one target per
case, generated by the severities_test() macro. check_results() reads
"<output_dir>/result.txt" and calls sys.exit(1) when it finds defects of the
requested severities or checker/bug names, so this driver copies the fixture
into a temp dir, runs check_results(), and compares the outcome against the
expected pass/fail.
"""

import argparse
import os
import shutil
import sys
import tempfile

from src.common import check_results


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments"""
    parser = argparse.ArgumentParser(
        description=(
            "Run common.check_results() on a result.txt fixture and assert "
            "whether it passes or fails for the given severities."
        )
    )
    parser.add_argument(
        "--file",
        required=True,
        help="Path to the result.txt fixture to check.",
    )
    parser.add_argument(
        "--severities",
        default=None,
        help=(
            "Severities and/or checker (bug) names to fail on."
        ),
    )
    parser.add_argument(
        "--expect",
        required=True,
        choices=["pass", "fail"],
        help="Expected outcome: 'pass' (no defects) or 'fail' (defects).",
    )
    return parser.parse_args()


def run(fixture: str, severities) -> bool:
    """
    Run check_results() on the fixture.

    Returns True if the analysis passed (no SystemExit), False if it failed
    (check_results called sys.exit).
    """
    output_dir = tempfile.mkdtemp()
    try:
        shutil.copyfile(fixture, os.path.join(output_dir, "result.txt"))
        try:
            check_results(
                output_dir=output_dir, log=None, severities=severities
            )
        except SystemExit:
            return False
        return True
    finally:
        shutil.rmtree(output_dir, ignore_errors=True)


def main() -> int:
    """Entry point: run the check and compare against the expectation"""
    args = parse_args()
    if not os.path.isfile(args.file):
        print(f"Fixture not found: {args.file}")
        return 1

    passed = run(args.file, args.severities)
    expected_pass = args.expect == "pass"

    if passed == expected_pass:
        outcome = "passed" if passed else "failed"
        print(f"OK: check_results({args.severities!r}) {outcome} as expected")
        return 0

    print(
        f"FAIL: expected check_results({args.severities!r}) to "
        f"{args.expect}, but it {'passed' if passed else 'failed'}"
    )
    return 1


if __name__ == "__main__":
    sys.exit(main())
